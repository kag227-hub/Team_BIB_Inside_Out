"use strict";
const byId = id => document.getElementById(id);
const percent = x => x == null ? "—" : (100 * x).toFixed(1) + "%";
const pp = x => x == null ? "—" : x.toFixed(2) + " pp";
function table(target, labels, rows) {
  const grid = document.createElement("table");
  const head = grid.createTHead().insertRow();
  for (const label of labels) {
    const cell = document.createElement("th");
    cell.scope = "col";
    cell.textContent = label;
    head.append(cell);
  }
  const body = grid.createTBody();
  for (const row of rows) {
    const tr = body.insertRow();
    for (const value of row) tr.insertCell().textContent = value ?? "—";
  }
  target.replaceChildren(grid);
}
async function start() {
  const response = await fetch("outputs/v0_dashboard.json");
  if (!response.ok) throw new Error("Missing v0_dashboard.json");
  const data = await response.json();
  byId("status").textContent = data.source_kind === "synthetic"
    ? "SYNTHETIC DEMO · These example responses were constructed to exercise the pipeline. They were not generated by the named models."
    : "COLLECTED PILOT · Exploratory data. Run: " + data.run_id;
  const model = byId("model"), arm = byId("arm");
  [...new Set(data.rows.map(r => r.model_id))].forEach(x => model.add(new Option(x, x)));
  [...new Set(data.rows.map(r => r.arm))].sort().forEach(x => arm.add(new Option(x.replaceAll("_", " "), x)));
  function render() {
    const match = r => (!model.value || r.model_id === model.value)
      && (!arm.value || r.arm === arm.value || r.arm === "control");
    table(byId("summary"), ["Model", "Emotion", "Arm", "Decision pairs", "Gain sell rate", "Loss sell rate", "Sell gap", "Rating gap"],
      data.summary.filter(match).map(r => [r.model_id, r.emotion, r.arm,
        r.complete_pairs + "/" + r.expected_pairs, percent(r.gain_sell_rate),
        percent(r.loss_sell_rate), pp(r.gap_pp), r.rating_gap]));
    const rows = data.rows.filter(match);
    byId("counts").textContent = "Showing " + rows.length + " of " + data.rows.length + " response rows. Filters above include the neutral control for reference.";
    table(byId("rows"), ["Model", "Persona", "Company", "Return", "Decision", "Rating"],
      rows.map(r => [r.model_id, r.persona_id, r.company, r.signed_return_pct + "%", r.decision_raw, r.rating]));
  }
  model.addEventListener("change", render);
  arm.addEventListener("change", render);
  render();
}
start().catch(() => {
  byId("status").textContent = "Could not load the outputs. Run python run_all.py and serve the repository over HTTP.";
});
